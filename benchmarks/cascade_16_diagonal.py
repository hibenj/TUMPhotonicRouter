"""16-mode cascade benchmark, diagonal layout.

Generated by `cascade.py`.
"""

from __future__ import annotations

from gdsfactory.schematic import Schematic

from benchmarks.cascade import build_cascade_schematic, internal_delays_um, node_types

N_MODES = 16
LAYOUT = "diagonal"

NODE_TYPES = node_types(N_MODES)
INTERNAL_DELAYS_UM = internal_delays_um(N_MODES)


def build_schematic() -> Schematic:
    """Build the 16-mode diagonal cascade benchmark schematic."""
    return build_cascade_schematic(N_MODES, LAYOUT)


if __name__ == "__main__":
    from photonic_router.records.layout_from_schematic import layout_from_schematic

    schematic = build_schematic()
    print("Schematic instances:", list(schematic.netlist.instances.keys()))
    print("Schematic placements:", list(schematic.placements.keys()))
    print("\nNets defined:")
    for net_name, bundle in schematic.netlist.routes.items():
        print(f"  - {net_name}: {bundle.links}")
    print(f"\nTotal nets: {len(schematic.netlist.routes)}")

    layout = layout_from_schematic(schematic)
    print(f"Opening unrouted benchmark layout: {layout.name}")
    layout.show()
