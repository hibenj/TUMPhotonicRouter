def build_schematic() -> Schematic:
    """Build the LiDAR Clements 8x8 benchmark schematic."""
    pdk = get_generic_pdk()
    pdk.activate()

    schematic = Schematic()

    for name, component, settings_group, x, y, rotation, mirror in INSTANCE_SPECS:
        schematic.add_instance(
            name,
            Instance(
                component=component,
                settings=dict(SETTINGS_BY_GROUP[settings_group]),
            ),
            Placement(x=x, y=y, rotation=rotation, mirror=mirror),
        )

    for name, p1, p2 in NET_SPECS:
        schematic.add_net(Net(p1=p1, p2=p2, name=name))

    return schematic


