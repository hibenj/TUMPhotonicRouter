"""Write the type stub of the Rust extension, ``python/photonic_router/_rust.pyi``.

The extension ships no static types, so every value it returns is ``Any`` to
mypy and the whole Python side above it loses type checking. PyO3 records the
signature of every class, method and function it exports
(``__text_signature__``) and the docstrings; this script reads them off the
built module and writes a stub with those signatures, ``Any``-typed where the
extension says nothing more. Regenerate after any change to ``crates/router-py/``:

    .venv/bin/python scripts/generate_rust_stubs.py            # rewrite
    .venv/bin/python scripts/generate_rust_stubs.py --check    # verify

``tests/test_rust_stub.py`` runs the check so the stub cannot drift.
"""

from __future__ import annotations

import inspect
import subprocess
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "python"))

import photonic_router._rust as rust

STUB = ROOT / "python" / "photonic_router" / "_rust.pyi"
HEADER = """# Type stub of the PyO3 extension ``photonic_router._rust``.
# Generated by ``scripts/generate_rust_stubs.py`` from the built module; do not
# edit by hand. Parameters and results the extension does not type are ``Any``.

from typing import Any

"""


def _signature(obj: object, *, method: bool) -> str:
    text = getattr(obj, "__text_signature__", None)
    if not text:
        return "(self, *args: Any, **kwargs: Any)" if method else "(*args: Any, **kwargs: Any)"
    text = text.replace("($self, ", "(self, ").replace("($self)", "(self)")
    text = text.replace("($cls, ", "(cls, ").replace("($cls)", "(cls)")
    try:
        sig = inspect.signature(obj)
    except (TypeError, ValueError):
        return text
    params = []
    for p in sig.parameters.values():
        if p.name in ("self", "cls"):
            params.append(p.replace(annotation=inspect.Parameter.empty))
        elif p.kind in (p.VAR_POSITIONAL, p.VAR_KEYWORD):
            params.append(p.replace(annotation=Any))
        else:
            params.append(p.replace(annotation=Any))
    rendered = str(sig.replace(parameters=params, return_annotation=inspect.Signature.empty))
    return rendered.replace("= Ellipsis", "= ...")


def render() -> str:
    out = [HEADER]
    for name in sorted(dir(rust)):
        if name.startswith("_"):
            continue
        obj = getattr(rust, name)
        if inspect.isclass(obj):
            out.append(f"class {name}:")
            body: list[str] = []
            init_sig = getattr(obj, "__text_signature__", None)
            if init_sig:
                sig = _signature(obj, method=False)
                sig = "(self, " + sig[1:] if sig != "()" else "(self)"
                body.append(f"    def __init__{sig} -> None: ...")
            for attr in sorted(vars(obj)):
                if attr.startswith("_"):
                    continue
                member = vars(obj)[attr]
                if inspect.isroutine(member) or inspect.ismethoddescriptor(member):
                    body.append(
                        f"    def {attr}{_signature(getattr(obj, attr), method=True)} -> Any: ..."
                    )
                elif inspect.isgetsetdescriptor(member) or isinstance(member, property):
                    body.append("    @property")
                    body.append(f"    def {attr}(self) -> Any: ...")
            out.extend(body or ["    ..."])
            out.append("")
        elif inspect.isroutine(obj):
            out.append(f"def {name}{_signature(obj, method=False)} -> Any: ...")
            out.append("")
        else:
            out.append(f"{name}: Any")
            out.append("")
    text = "\n".join(out).rstrip() + "\n"
    return _formatted(text)


def _formatted(text: str) -> str:
    """The stub as `ruff format` lays it out, so the checked-in file is formatted."""
    try:
        result = subprocess.run(
            [sys.executable, "-m", "ruff", "format", "--stdin-filename", STUB.name, "-"],
            input=text,
            capture_output=True,
            text=True,
            check=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return text
    return result.stdout


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = STUB.read_text() if STUB.exists() else ""
        if current != text:
            print(
                f"{STUB.relative_to(ROOT)} is out of date; regenerate it with {Path(__file__).name}"
            )
            return 1
        print("stub up to date")
        return 0
    STUB.write_text(text)
    print(f"wrote {STUB.relative_to(ROOT)} ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
